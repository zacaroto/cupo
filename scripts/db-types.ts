// Regenerates packages/shared/src/database.types.ts from the local stack
// (schemas public and audit, KTD10), or with --check fails when the committed
// file differs from what the running database produces.
//
//   npm run db:types            # rewrite the file
//   npm run db:types -- --check # exit 1 on drift (CI)
//
// Runs on plain Node >= 22.18 (type stripping) and Node 24/25.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const repoRoot = resolve(import.meta.dirname, "..");
const target = resolve(repoRoot, "packages/shared/src/database.types.ts");
const check = process.argv.includes("--check");

const banner = `// Generated by \`npm run db:types\` (supabase gen types, schemas public and audit).
// Do not edit by hand; CI fails when this file differs from the migrations.
`;

const generated = execFileSync(
  "npx",
  ["supabase", "gen", "types", "--lang", "typescript", "--schema", "public,audit"],
  { cwd: repoRoot, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], timeout: 120_000 },
);
const next = banner + generated.replace(/\s+$/, "") + "\n";

if (check) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    console.error(`db:types --check: ${target} does not exist; run npm run db:types`);
    process.exit(1);
  }
  if (current !== next) {
    console.error("db:types --check: packages/shared/src/database.types.ts is out of date; run npm run db:types and commit the result");
    process.exit(1);
  }
  console.log("db:types --check: generated types are current");
} else {
  writeFileSync(target, next);
  console.log(`db:types: wrote ${target}`);
}
